// ຈັດ email ໃຫ້ເປັນຮູບແບບດຽວກັນ ກ່ອນບັນທຶກ ຫຼືປຽບທຽບ:
//   trim()        = ລຶບຍະຫວ່າງຫົວ-ທ້າຍ ເຊັ່ນ " noy@gmail.com " → "noy@gmail.com"
//   toLowerCase() = ປ່ຽນເປັນຕົວນ້ອຍ ເຊັ່ນ "Noy@Gmail.com" → "noy@gmail.com"
// ສະນັ້ນພິມຕົວໃຫຍ່ ຫຼືຕົວນ້ອຍ ກໍຖືວ່າເປັນ email ດຽວກັນ
export function normalizeEmail(email: string): string {
  return email.trim().toLowerCase();
}

// ຮັບ email ເຂົ້າມາ ແລ້ວສົ່ງຄືນ true (ຖືກຕ້ອງ) ຫຼື false (ບໍ່ຖືກ)
export function isValidEmail(email: string): boolean {
  // ກວດດ້ວຍ Regular Expression (regex = ຮູບແບບສຳລັບກວດຂໍ້ຄວາມ):
  //   ^       = ເລີ່ມຕົ້ນຂໍ້ຄວາມ
  //   [^\s@]+ = ຕົວອັກສອນໃດກໍໄດ້ 1 ຕົວຂຶ້ນໄປ ທີ່ບໍ່ແມ່ນຍະຫວ່າງ ແລະບໍ່ແມ່ນ @
  //   @       = ຕ້ອງມີເຄື່ອງໝາຍ @
  //   \.      = ຕ້ອງມີຈຸດ (.) ລະຫວ່າງໂດເມນ ແລະສະກຸນ
  //   $       = ຈົບຂໍ້ຄວາມ
  // ຮູບແບບ: ຊື່@ໂດເມນ.ສະກຸນ
  // ຕົວຢ່າງທີ່ຖືກ: noy@gmail.com, somchai.k@laotel.la
  // ຕົວຢ່າງທີ່ຜິດ: noy@gmail (ບໍ່ມີຈຸດ), noy.gmail.com (ບໍ່ມີ @)
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(normalizeEmail(email));
}
