// ຮັບເບີໂທເຂົ້າມາ ແລ້ວສົ່ງຄືນ true (ຖືກຕ້ອງ) ຫຼື false (ບໍ່ຖືກ)
export function isValidLaoPhone(phone: string): boolean {
  // ລຶບຍະຫວ່າງອອກກ່ອນ ເຊັ່ນ "020 5555 5555" → "02055555555"
  const digits = phone.replaceAll(" ", "");

  // ກວດດ້ວຍ Regular Expression (regex = ຮູບແບບສຳລັບກວດຂໍ້ຄວາມ):
  //   ^         = ເລີ່ມຕົ້ນຂໍ້ຄວາມ
  //   (020|030) = ຕ້ອງຂຶ້ນຕົ້ນດ້ວຍ 020 ຫຼື 030
  //   \d{7,8}   = ຕາມດ້ວຍຕົວເລກ 7 ຫາ 8 ຕົວ (\d = ຕົວເລກ 0-9)
  //   $         = ຈົບຂໍ້ຄວາມ (ບໍ່ໃຫ້ມີຫຍັງຕໍ່ທ້າຍອີກ)
  // ຕົວຢ່າງທີ່ຖືກ: 02055555555 (11 ຕົວ), 0305555555 (10 ຕົວ)
  return /^(020|030)\d{7,8}$/.test(digits);
}
